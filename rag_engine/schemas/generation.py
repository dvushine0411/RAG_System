"""
System Role: Pydantic schemas defining LLM streaming generation requests, SSE event payloads, token usage metrics, and query pipeline DTOs.
Inputs: User requests for direct generation or end-to-end RAG query streaming.
Outputs: Strongly-typed validation models enforcing SSE payload structure and API contracts.
Ref: ARCHITECTURE.md §2.2 Phase B step 6-7, Phase 6
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from schemas.augmentation import ChatMessageDTO, CitationMetadata
from schemas.retrieval import RetrievalFilter


class TokenUsageDTO(BaseModel):
    """
    Standardized token consumption metrics for prompt input and completion output.
    """
    prompt_tokens: int = Field(default=0, description="Tokens consumed by input prompt")
    completion_tokens: int = Field(default=0, description="Tokens generated in completion output")
    total_tokens: int = Field(default=0, description="Total tokens consumed")


class StreamTokenData(BaseModel):
    """
    SSE payload emitted for 'token' events containing text deltas.
    """
    delta: str = Field(..., description="Incremental text generated by the LLM")


class StreamCitationsData(BaseModel):
    """
    SSE payload emitted for 'citations' events listing referenced source documents.
    """
    citations: List[CitationMetadata] = Field(default_factory=list, description="List of cited source chunks")


class StreamDoneData(BaseModel):
    """
    SSE payload emitted for 'done' events signaling completion of stream.
    """
    finish_reason: str = Field(default="stop", description="Reason streaming finished ('stop', 'length', etc.)")
    token_usage: TokenUsageDTO = Field(default_factory=TokenUsageDTO, description="Aggregated token statistics")
    latency_ms: float = Field(..., description="Total execution duration in milliseconds")
    used_citation_ids: List[int] = Field(
        default_factory=list,
        description="Citation ids actually referenced as [n] in the answer (subset of the 'citations' event)",
    )
    retrieval_query: Optional[str] = Field(
        default=None,
        description="Query sent to retrieval when it differs from the user's question (query rewriting)",
    )


class StreamErrorData(BaseModel):
    """
    SSE payload emitted for 'error' events if streaming fails mid-flight.
    """
    message: str = Field(..., description="Human-readable error description")
    error_code: str = Field(default="STREAM_ERROR", description="Machine-readable error identifier")


class GenerateStreamRequest(BaseModel):
    """
    Request payload for standalone prompt generation streaming.
    """
    messages: List[ChatMessageDTO] = Field(..., min_length=1, description="Sequence of chat messages")
    model: Optional[str] = Field(default=None, description="Model identifier override")
    temperature: Optional[float] = Field(default=None, ge=0.0, le=2.0, description="Sampling temperature override")
    max_tokens: Optional[int] = Field(default=None, gt=0, description="Maximum tokens to generate")
    citations: Optional[List[CitationMetadata]] = Field(default=None, description="Pre-assembled citations to emit")


class QueryStreamRequest(BaseModel):
    """
    Request payload for complete End-to-End RAG query streaming (Retrieve -> Augment -> Stream).
    """
    query: str = Field(..., min_length=1, description="User question or search query")
    conversation_history: Optional[List[ChatMessageDTO]] = Field(
        default=None,
        description="Prior conversation history turns for multi-turn grounding"
    )
    filter: Optional[RetrievalFilter] = Field(
        default=None,
        description="Metadata filters applied during HNSW vector retrieval"
    )
    model: Optional[str] = Field(default=None, description="LLM provider model identifier override")
    retrieval_top_k: Optional[int] = Field(default=None, gt=0, description="Vector search candidate count override")
    rerank_top_n: Optional[int] = Field(default=None, gt=0, description="Reranked chunk count override")
    temperature: Optional[float] = Field(default=None, ge=0.0, le=2.0, description="Sampling temperature override")
    max_tokens: Optional[int] = Field(default=None, gt=0, description="Maximum tokens to generate")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Optional telemetry or query metadata")
